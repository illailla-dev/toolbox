    // 코어 연산 엔진 함수
    function generateUnicodeSubset() {
        const selectedType = $('#subset-type').val();
        let targetText = charDatabase[selectedType];

        // 초경량 버전일 경우 기본 영문/숫자/특수기호 바인딩 결합
        if (selectedType === 'basic-chars') {
            const asciiComponents = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()_+-=[]{}|;':\",./<>?\\`~ ";
            targetText = asciiComponents + targetText;
        }

        // 1. 리스트 창에 실시간 글자 소스 뿌리기
        $('#raw-text-area').val(targetText);

        // 2. 글자 한 자 한 자 파싱하여 유니코드 배열화 추출 (CSS unicode-range 포맷팅)
        const unicodeList = [];
        for (let i = 0; i < targetText.length; i++) {
            const code = targetText.charCodeAt(i).toString(16).toUpperCase();
            // 4자리 포맷 맞춤 패딩 추가
            const paddedCode = 'U+' + code.padStart(4, '0');
            unicodeList.push(paddedCode);
        }

        // 중복 유니코드 제거 후 쉼표 조립
        const uniqueUnicodes = [...new Set(unicodeList)];
        const cssRangeString = `unicode-range: ${uniqueUnicodes.join(', ')};`;

        $('#unicode-range-area').val(cssRangeString);
    }

    // [이벤트] 텍스트 리스트 복사 버튼
